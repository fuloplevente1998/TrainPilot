const assert=require('node:assert/strict');
const fs=require('node:fs');
const java=fs.readFileSync('android/app/src/main/java/com/repforge/app/NativeFilesPlugin.java','utf8');
const backupPath=fs.existsSync('www/backup.js')?'www/backup.js':'www/app.js';
const backup=fs.readFileSync(backupPath,'utf8');
assert.match(backup,/JSON\.stringify\(makeBackup\(\),null,2\)/,'backup JSON payload must be serialized before native save');
assert.match(backup,/nativeFiles\(\)\.save\(\{name,data\}\)/,'native backup must pass the serialized JSON payload');
assert.match(backup,/if\(!r\.verified\)/,'UI must require native verification before reporting success');
assert.match(java,/createPendingFile\(bytes\)/,'native save must stage backup bytes before opening the picker');
assert.match(java,/out\.getFD\(\)\.sync\(\)/,'staged backup must be flushed to the internal temp file');
assert.match(java,/call\.getData\(\)\.remove\("data"\)/,'large backup JSON must be removed from PluginCall before Activity state persistence');
assert.match(java,/protected Bundle saveInstanceState\(\)/,'plugin must persist only lightweight pending-export state');
assert.match(java,/protected void restoreState\(Bundle state\)/,'plugin must restore pending-export state after Activity recreation');
assert.match(java,/openOutputStream\(uri, "w"\)/,'selected SAF document must be written from the staged temp file');
assert.match(java,/actual\.length <= 0 \|\| !Arrays\.equals\(expected, actual\)/,'0-byte or mismatched exports must fail verification');
assert.match(java,/clearPendingSave\(source\)/,'temporary export data must be cleaned up after callback handling');
const src=require('../SOURCE_VERSION.json');
assert.equal(src.version,'1.7.0');
assert.equal(src.versionCode,2659);
console.log('PASS: lifecycle-safe native backup export stages data internally, keeps Activity state small, verifies exact bytes, and cleans temp data.');
