package com.example.ui.theme

import androidx.compose.ui.graphics.Color

enum class PaletteCategory {
    BASIC,
    VIVID
}

data class TrainPilotPalette(
    val id: Int,
    val category: PaletteCategory,
    val nameHu: String,
    val nameEn: String,
    val nameDe: String,
    val nameRo: String,
    val isDark: Boolean,
    val background: Color,
    val surface: Color,
    val surfaceElevated: Color,
    val cardBorder: Color,
    val primary: Color,
    val primaryBright: Color,
    val onPrimary: Color,
    val secondary: Color,
    val tertiary: Color,
    val textPrimary: Color,
    val textSecondary: Color,
    val sleepAccent: Color = Color(0xFFA855F7),
    val heartAccent: Color = Color(0xFFEF4444),
    val stepsAccent: Color = Color(0xFF06B6D4),
    val energyAccent: Color = Color(0xFF22C55E),
    val success: Color = Color(0xFF22C55E),
    val warning: Color = Color(0xFFF59E0B),
    val danger: Color = Color(0xFFEF4444)
) {
    val surfaceCard: Color get() = surface
    val textMuted: Color get() = textSecondary.copy(alpha = 0.72f)

    fun localizedName(langCode: String): String = when (langCode) {
        "EN" -> nameEn
        "DE" -> nameDe
        "RO" -> nameRo
        else -> nameHu
    }

    fun localizedName(lang: com.example.model.AppLanguage): String = localizedName(lang.code)
}

